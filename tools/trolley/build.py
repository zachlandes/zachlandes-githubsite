#!/usr/bin/env python3
"""Build the trolley post from the article's generator, in the site's design.

    python3 tools/trolley/build.py path/to/trolley-bench/site

The generator (its build.py) writes a.html, one self-contained page that reads results.json and draws
most of its tables and one chart with script. This opens that page in headless Chrome, takes the
rendered page, and rewrites it into the site's post markup: the article's text and headings as the post's own
prose, the article's side notes as the site's margin notes, its charts and tables as figures, and each
diorama as a frame of the collage pane (pane.py) driven by assets/trolley/dioramas.js.

It writes three generated files, _unlisted/trolley.html, assets/trolley/pane.html and
assets/trolley/results.js; assets/trolley/{trolley.css,dioramas.js} are written by hand.
Set CHROME to the browser binary if it is not at the macOS default.
"""
