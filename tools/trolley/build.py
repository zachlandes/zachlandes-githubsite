#!/usr/bin/env python3
"""Build the trolley post from the article's review reader, in the site's design.

    python3 tools/trolley/build.py READER_URL path/to/trolley-bench/site

The article is written in its review reader (full_preview.py, beside its copy.md), which applies the copy to
the generator's a.html, refreshes the tables and charts from the frozen results, and serves the page with
its data. This opens that page in headless Chrome, takes the rendered page, and rewrites it into the site's
post markup: the article's text and headings as the post's own prose, its notes as the site's margin notes,
its charts and tables as figures, and each diorama as a frame of the collage pane (pane.py, built from the
generator's a.html) driven by assets/trolley/dioramas.js.

It writes the post and assets/trolley/{pane.html,results.js,results.json,selection-snapshot.json};
assets/trolley/{trolley.css,dioramas.js} are written by hand.
Set CHROME to the browser binary if it is not at the macOS default.
"""
import html
import json
import os
import pathlib
import re
import subprocess
import sys
import urllib.request
from html.parser import HTMLParser

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pane  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parents[2]
ASSETS = "/assets/trolley"
DATE = "2026-10-14"
POST = ROOT / "_posts" / f"{DATE}-trolley-problem.html"
CHROME = os.environ.get("CHROME", "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome")
GENERATED = "Generated by tools/trolley/build.py from the article's review reader; change the article there and rerun"
# The link card quotes the end of the article's opening paragraph rather than any new copy; the article has no dek,
# so it is card_description, which the page never shows. The preview image is a diorama mid-run, captured at 1200x630
CARD = "People are calling this new breed of model ‘decision models’. So naturally, I decided to ask Jev and its ilk to decide the Trolley Problem."
CARD_IMAGE = "/assets/og/trolley-problem.jpg"

# Must never reach the public repository: local paths and local or tailnet hosts (100.64/10 is the tailnet range)
PRIVATE = re.compile(r"/Users/|/private/|/home/|127\.0\.0\.1|localhost|\.ts\.net|\btail[0-9a-f]{6}\b|\b100\.(?:6[4-9]|[7-9]\d|1[01]\d|12[0-7])\.", re.I)


# ---------- The rendered page as a small tree ----------

VOID = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "source", "track", "wbr"}


class Node:
    def __init__(self, tag, attrs, parent=None):
        self.tag, self.attrs, self.parent, self.children = tag, dict(attrs), parent, []

    @property
    def cls(self):
        return set((self.attrs.get("class") or "").split())

    def kids(self):
        return [c for c in self.children if isinstance(c, Node)]

    def find_all(self, pred):
        for c in self.kids():
            if pred(c):
                yield c
            yield from c.find_all(pred)

    def find(self, pred):
        return next(self.find_all(pred), None)

    def text(self):
        return "".join(c if isinstance(c, str) else c.text() for c in self.children)

    def inner(self):
        return "".join(html.escape(c, quote=False) if isinstance(c, str) else c.outer() for c in self.children)

    def outer(self):
        a = "".join(f' {k}' if v is None else f' {k}="{html.escape(v, quote=True)}"' for k, v in self.attrs.items())
        return f"<{self.tag}{a}>" + ("" if self.tag in VOID else self.inner() + f"</{self.tag}>")


class Tree(HTMLParser):
    def __init__(self, src):
        super().__init__(convert_charrefs=True)
        self.root = self.cur = Node("#root", {})
        self.feed(src)

    def handle_starttag(self, tag, attrs):
        n = Node(tag, attrs, self.cur)
        self.cur.children.append(n)
        if tag not in VOID:
            self.cur = n

    def handle_startendtag(self, tag, attrs):
        self.cur.children.append(Node(tag, attrs, self.cur))

    def handle_endtag(self, tag):
        n = self.cur
        while n is not self.root and n.tag != tag:
            n = n.parent
        if n is not self.root:
            self.cur = n.parent

    def handle_data(self, data):
        self.cur.children.append(data)


def by_class(*names):
    return lambda n: all(c in n.cls for c in names)


def by_id(i):
    return lambda n: n.attrs.get("id") == i


def one(root, pred, what):
    found = list(root.find_all(pred))
    assert len(found) == 1, f"expected one {what}, found {len(found)}"
    return found[0]


def rendered(url):
    """The article after its script has run, as Chrome serialises it"""
    out = subprocess.run([CHROME, "--headless=new", "--disable-gpu", "--window-size=1440,900", "--virtual-time-budget=10000",
                          "--dump-dom", url], capture_output=True, text=True, timeout=120)
    assert 'id="own-server-chart"' in out.stdout and "<table" in out.stdout, "the article's charts never rendered"
    return out.stdout


def fetch(url):
    with urllib.request.urlopen(url, timeout=60) as r:
        return r.read().decode()


# ---------- The article, rewritten into the site's post markup ----------

def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", html.unescape(re.sub(r"<[^>]+>", "", s)).lower()).strip("-")


REPO = "https://github.com/zachlandes/trolley-bench/blob/main/"
# The reader serves these beside the page; on the site they are copies in assets/trolley or the files in the public repository
LINKS = {
    "/selection-snapshot.json": f"{ASSETS}/selection-snapshot.json",
    "/results.json": f"{ASSETS}/results.json",
    "/models.yaml": REPO + "models.yaml",
    "/panel.json": REPO + "results/v2/panel.json",
    "/analysis-plan.md": REPO + "ANALYSIS-PLAN-v2.md",
    "/analysis-deviations.md": REPO + "ANALYSIS-PLAN-v2-deviations.md",
}


def clean(markup):
    """The reader's own links, pointed at where the site keeps them"""
    for old, new in LINKS.items():
        markup = markup.replace(f'href="{old}"', f'href="{new}"')
    return markup


class Post:
    def __init__(self, data, notes):
        self.out, self.count, self.data, self.notes = [], 0, data, notes

    def add(self, s):
        self.out.append(clean(s))

    def para(self, n, cls=""):
        refs = list(n.find_all(by_class("st-note-ref")))
        for r in refs:
            r.parent.children.remove(r)
        attr = f' class="{cls}"' if cls else ""
        body = n.inner().strip()
        if not refs:
            return self.add(f"<p{attr}>{body}</p>")
        assert len(refs) == 1, "one note to a paragraph"
        k, (side, below) = self.next_note(refs[0])
        self.add(f'<div class="has-note">\n<p{attr}>{body}<sup class="ref"><a href="#note-{k}" id="ref-{k}" aria-label="Note {k}">{k}</a></sup>{side}</p>\n{below}\n</div>')

    def next_note(self, ref):
        """A note of the article's as the site's margin note: hung in the margin on wide screens, a footnote below on narrow ones"""
        self.count += 1
        k = self.count
        assert ref.attrs.get("href") == f"#reader-note-{k}", f"note {k} is out of order"
        item = self.notes[k]
        paras = [p for p in item.kids() if p.tag == "p"]
        assert paras, f"note {k} has no text"
        spans = "".join(f'<span class="sn-p">{p.inner().strip()}</span>' for p in paras)
        side = f'<span class="sidenote" aria-hidden="true"><span class="n">{k}</span>{spans}</span>'
        below = f'<aside class="note" id="note-{k}"><span class="n" aria-hidden="true">{k}</span>{spans}</aside>'
        return k, (side, below)

    def heading(self, n, level):
        body = n.inner().strip()
        self.add(f'<h{level} id="{n.attrs.get("id") or slug(body)}">{body}</h{level}>')

    def body(self, container):
        kids = container.kids()
        i = 0
        while i < len(kids):
            n = kids[i]
            c = n.cls
            if n.tag == "h1" or "st-byline" in c or "st-try" in c or "reader-notes" in c:
                # The title is the layout's; the play buttons are hidden in the reader; the notes go beside their paragraphs
                pass
            elif n.tag == "h2" and "st-sub" in c:
                # His two-line appendix headings ("Appendix A:", then its title) stay one heading on two lines
                nxt = kids[i + 1] if i + 1 < len(kids) else None
                if nxt is not None and nxt.tag == "h2" and "st-sub" in nxt.cls:
                    a, b = n.inner().strip(), nxt.inner().strip()
                    self.add(f'<h2 id="{slug(a)}"><span class="h-lead">{a}</span> {b}</h2>')
                    i += 1
                else:
                    self.heading(n, 2)
            elif n.tag == "h3" and "st-sub" in c:
                self.heading(n, 3)
            elif n.tag == "p" and "st-turn" in c:
                self.para(n, "pivot")
            elif n.tag == "p" and "st-lede" in c:
                self.para(n)
            elif n.tag == "p" and "st-small" in c:
                self.para(n, "small")
            elif "st-anno" in c:
                for p in n.kids():
                    assert p.tag == "p", "a note sits beside paragraphs"
                    self.para(p)
            elif "st-runnote" in c:
                self.add(f'<p class="runnote">{n.inner().strip()}</p>')
            elif "dio-slot" in c:
                self.diorama(n)
            elif n.tag == "figure":
                self.add(f'<figure class="wide chart {" ".join(sorted(x for x in c if x.startswith("st-")))}"{id_of(n)}>{n.inner().strip()}</figure>')
            elif "st-smgrid" in c:
                self.add(f'<figure class="wide chart st-multiples"><div class="st-smgrid">{n.inner().strip()}</div></figure>')
            elif "tbl-wrap" in c:
                self.add(table_box(n))
            elif n.tag == "nav":
                ul = one(n, lambda x: x.tag == "ul", "index list")
                ul.attrs.pop("class", None)
                self.add(n.outer())
            elif n.tag == "details":
                self.details(n)
            elif n.tag == "ol":
                self.add(f'<ol class="{" ".join(x for x in c if x == "st-refs")}">{n.inner().strip()}</ol>')
            elif n.tag == "section" and "st-story" in c or n.tag == "div" and ("st-body" in c or "st-sources" in c):
                if n.attrs.get("id"):
                    self.add(f'<span id="{n.attrs["id"]}"></span>')
                self.body(one(n, lambda x: x.parent is n and "st-body" in x.cls, "section body") if n.tag == "section" else n)
            else:
                raise AssertionError(f"no rule for <{n.tag} class={n.attrs.get('class')!r}>: {n.text()[:60]!r}")
            i += 1

    def details(self, d):
        summary = one(d, lambda x: x.tag == "summary", "summary")
        parts = []
        for k in d.kids():
            c = k.cls
            if k is summary:
                continue
            if "tbl-wrap" in c:
                parts.append(table_box(k))
            elif k.tag == "p":
                parts.append(f'<p class="small">{k.inner().strip()}</p>')
            elif "st-smgrid" in c:
                parts.append(f'<div class="st-smgrid">{k.inner().strip()}</div>')
            else:
                raise AssertionError(f"no rule in a fold for <{k.tag} class={k.attrs.get('class')!r}>")
        self.add(f'<details{id_of(d)}>\n<summary>{summary.inner().strip()}</summary>\n<div class="details-body">\n' + "\n".join(parts) + "\n</div>\n</details>")

    def diorama(self, slot):
        fig = one(slot, lambda x: x.tag == "figure" and "dio" in x.cls, "diorama")
        cap = one(fig, lambda x: x.tag == "figcaption", "diorama caption")
        self.add(dio_figure(slot.attrs["data-diorama-slot"], fig.attrs["data-preset"], cap, self.data))


def id_of(n):
    return f' id="{n.attrs["id"]}"' if n.attrs.get("id") else ""


def table_box(wrap):
    t = one(wrap, lambda x: x.tag == "table", "table")
    rest = "".join(k.outer() for k in wrap.kids() if k is not t and k.tag == "p")
    label = html.escape(re.sub(r"\s+", " ", (t.find(lambda x: x.tag == "th") or t).text()).strip()[:40], quote=True)
    return f'<div class="table-box scroller" tabindex="0" role="region" aria-label="Table: {label}">{t.outer()}</div>{rest}'


# ---------- Dioramas ----------

QUESTION = """  <div class="dio-q dio-row" data-margin>
    <span class="dio-lab">What <span class="dio-q-who">Jev</span> was asked</span>
    <div>
      <blockquote class="dio-q-text"></blockquote>
      <p class="dio-q-line"><q class="dio-q-ask"></q><button type="button" class="dio-q-more" aria-expanded="false" hidden>Show the full text</button></p>
    </div>
  </div>"""
ACTIONS = """  <div class="dio-actions">
    <button class="go" type="button" data-act="send">Send the trolley</button>
    <button type="button" data-act="reset">Reset</button>
  </div>"""


def dio_figure(kind, preset, cap, data):
    """A preset scene, or with kind "end" the appendix's scene with every control"""
    first = re.sub(r"\s+", " ", next((c for c in cap.children if isinstance(c, str)), "")).strip()
    assert first, f"the {kind} scene has a caption"
    title = f"Trolley diorama: {first[0].lower() + first[1:]}"
    extra = "".join(k.outer() for k in cap.kids())
    caption = f'  <figcaption>{html.escape(first, quote=False)}{extra}</figcaption>'
    frame = f'  <iframe class="dio-frame" name="diorama-{kind}" src="{ASSETS}/pane.html" title="{html.escape(title, quote=True)}"{"" if kind == "start" else " loading=\"lazy\""}></iframe>'
    if kind != "end":
        return f'<figure class="dio" id="diorama-{kind}" data-preset="{preset}">\n{QUESTION}\n{frame}\n{ACTIONS}\n{caption}\n</figure>'
    scen, model, n, *rest = preset.split("|")
    p = "dio-end"
    setups = [(s["id"], s["label"]) for s in data["scenarios"]]
    pills = "".join(f'<button type="button" data-scenario="{s}" aria-pressed="{str(s == scen).lower()}">{html.escape(label)}</button>' for s, label in setups)
    opts = "".join(f'<option value="{s}"{" selected" if s == scen else ""}>{html.escape(label)}</option>' for s, label in setups)
    counts = "".join(f'<button type="button" data-n="{c}" aria-pressed="{str(str(c) == n).lower()}">{"nobody" if c == 0 else c}</button>' for c in (0, 1, 5, 20))
    every = sorted({c for s in data["scenarios"] if s["id"] == scen for w in s["wordings"] for c in w["ns"]})
    people = "".join(f'<option value="{c}"{" selected" if str(c) == n else ""}>{c}</option>' for c in every)
    models = [m for m in data["models"] if not m.get("baseline")] + [m for m in data["models"] if m.get("baseline")]
    robots = "".join(f'<option value="{m["id"]}"{" selected" if m["id"] == model else ""}>{html.escape(m["name"])}{" (untuned baseline)" if m.get("baseline") else ""}</option>' for m in models)
    order = f'<label class="dio-order"><input type="checkbox" name="order"{" checked" if rest[1:] == ["o2"] else ""}> <span>Side track described first</span></label>'
    controls = f"""  <div class="dio-controls" role="group" aria-label="Diorama setup">
    <div class="dio-row"><span class="dio-lab" id="{p}-l1">Setup</span><div class="pills" role="group" aria-labelledby="{p}-l1">{pills}</div><select id="{p}-setup" name="scenario" aria-labelledby="{p}-l1">{opts}</select></div>
    <div class="dio-row"><span class="dio-lab" id="{p}-l2">On the main track</span><div class="pills" role="group" aria-labelledby="{p}-l2">{counts}</div><label class="dio-count"><span class="dio-lab">People</span><select name="count">{people}</select></label></div>
    <div class="dio-row"><label class="dio-lab" for="{p}-model">Robot</label><div class="dio-pick"><select id="{p}-model" name="model">{robots}</select><label><span class="dio-lab">Wording</span><select name="wording"></select></label>{order}</div></div>
  </div>"""
    return f'<figure class="dio" id="diorama" data-preset="{preset}">\n{controls}\n{QUESTION}\n{frame}\n{ACTIONS}\n{caption}\n</figure>'


# ---------- Assembly ----------

def main(reader, bench):
    reader = reader.rstrip("/") + "/"
    article = (pathlib.Path(bench).resolve() / "a.html").read_text()
    js = fetch(reader + "figures/diorama/results.js")
    m = re.fullmatch(r"window\.DIO_DATA=(.*);\s*", js, re.S)
    assert m, "the reader's results are not where the build expects them"
    data = json.loads(m.group(1))
    snapshot = json.loads(fetch(reader + "selection-snapshot.json"))
    tree = Tree(rendered(reader)).root
    wrap = one(tree, by_class("wrap"), "page wrapper")
    title = html.unescape(re.sub(r"\s+", " ", one(tree, by_id("st-h"), "headline").text()).strip())
    notes = {int(li.attrs["id"].rsplit("-", 1)[1]): li for li in one(tree, by_class("reader-notes"), "notes").find_all(lambda x: x.tag == "li")}

    post = Post(data, notes)
    # The reader shows its story sections in page order; the rest of the wrapper is its hidden draft UI
    # (the old opening diorama, its loading card and theme switches) and the page foot
    for s in wrap.kids():
        if s.tag == "section" and "st-story" in s.cls and "st-parked" not in s.cls:
            post.body(one(s, lambda n: n.parent is s and "st-body" in n.cls, "section body"))
    assert post.count == len(notes), f"{len(notes) - post.count} notes have no reference"
    foot = one(wrap, by_class("foot"), "page foot")
    post.add('<p class="small">' + "<br>".join(html.escape(k.text().strip(), quote=False) for k in foot.kids()) + "</p>")

    text = "\n\n".join(post.out)
    opening = html.unescape(re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "", post.out[0])))
    assert CARD in opening, "the link card no longer quotes the article's opening; update CARD"
    page = (f"---\n# {GENERATED}\ntitle: {json.dumps(title, ensure_ascii=False)}\ndate: {DATE}\n"
            f"card_description: {json.dumps(CARD, ensure_ascii=False)}\nimage: {CARD_IMAGE}\n"
            # No excerpt: the raw block would split one
            'excerpt_separator: ""\n---\n'
            f'<link rel="stylesheet" href="{ASSETS}/trolley.css">\n{{% raw %}}\n{text}\n{{% endraw %}}\n'
            f'<script src="{ASSETS}/dioramas.js"></script>\n')
    # The post reads only what its figures use; the field below names a local report and never shows
    data.get("human", {}).pop("source_report", None)
    outputs = {
        POST: page,
        ROOT / "assets" / "trolley" / "pane.html": pane.build(article),
        ROOT / "assets" / "trolley" / "results.js": "window.DIO_DATA=" + json.dumps(data, separators=(",", ":"), ensure_ascii=False) + ";\n",
        ROOT / "assets" / "trolley" / "selection-snapshot.json": json.dumps(snapshot, indent=1, ensure_ascii=False) + "\n",
        ROOT / "assets" / "trolley" / "results.json": json.dumps(data, separators=(",", ":"), ensure_ascii=False) + "\n",
    }
    # Every root-relative link must be a page or file the site has
    unknown = sorted(set(re.findall(r'href="(/[^"#]*)"', text)) - set(LINKS.values()) - {"/"})
    assert not unknown, f"the post links files the site does not have: {unknown}"
    for path, out in outputs.items():
        hits = sorted({m.group(0) for m in PRIVATE.finditer(out)})
        assert not hits, f"{path.name} carries private text: {hits}"
        # Square brackets in prose are the article's draft placeholders, which never reach the site
        if path == POST:
            prose = re.sub(r"<(script|style|svg)\b.*?</\1>|<[^>]+>", " ", out, flags=re.S)
            left = re.findall(r"\[[^\]\n]{1,80}\]", prose)
            assert not left, f"the post still has placeholders: {left}"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(out)
        print(f"wrote {path.relative_to(ROOT)} ({len(out.encode()):,} bytes)")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
