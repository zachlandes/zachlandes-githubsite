# Must never reach the public repository: local paths and local or tailnet hosts (100.64/10 is the tailnet range)
PRIVATE = re.compile(r"/Users/|/private/|/home/|127\.0\.0\.1|localhost|\.ts\.net|\btail[0-9a-f]{6}\b|\b100\.(?:6[4-9]|[7-9]\d|1[01]\d|12[0-7])\.", re.I)


# ---------- The rendered page as a small tree ----------

VOID = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "source", "track", "wbr"}


class Node:
    def __init__(self, tag, attrs, parent=None):
        self.tag, self.attrs, self.parent, self.children = tag, dict(attrs), parent, []

    @property
    def cls(self):
        return set((self.attrs.get("class") or "").split())

    def kids(self):
        return [c for c in self.children if isinstance(c, Node)]

    def find_all(self, pred):
        for c in self.kids():
            if pred(c):
                yield c
            yield from c.find_all(pred)

    def find(self, pred):
        return next(self.find_all(pred), None)

    def text(self):
        return "".join(c if isinstance(c, str) else c.text() for c in self.children)

    def inner(self):
        return "".join(html.escape(c, quote=False) if isinstance(c, str) else c.outer() for c in self.children)

    def outer(self):
        a = "".join(f' {k}' if v is None else f' {k}="{html.escape(v, quote=True)}"' for k, v in self.attrs.items())
        return f"<{self.tag}{a}>" + ("" if self.tag in VOID else self.inner() + f"</{self.tag}>")


class Tree(HTMLParser):
    def __init__(self, src):
        super().__init__(convert_charrefs=True)
        self.root = self.cur = Node("#root", {})
        self.feed(src)

    def handle_starttag(self, tag, attrs):
        n = Node(tag, attrs, self.cur)
        self.cur.children.append(n)
        if tag not in VOID:
            self.cur = n

    def handle_startendtag(self, tag, attrs):
        self.cur.children.append(Node(tag, attrs, self.cur))

    def handle_endtag(self, tag):
        n = self.cur
        while n is not self.root and n.tag != tag:
            n = n.parent
        if n is not self.root:
            self.cur = n.parent

    def handle_data(self, data):
        self.cur.children.append(data)


def by_class(*names):
    return lambda n: all(c in n.cls for c in names)


def by_id(i):
    return lambda n: n.attrs.get("id") == i


def one(root, pred, what):
    found = list(root.find_all(pred))
    assert len(found) == 1, f"expected one {what}, found {len(found)}"
    return found[0]


def rendered(site):
    """The article after its script has run, as Chrome serialises it"""
    class Quiet(http.server.SimpleHTTPRequestHandler):
        def log_message(self, *a):
            pass
    handler = functools.partial(Quiet, directory=str(site))
    srv = http.server.ThreadingHTTPServer(("127.0.0.1", 0), handler)
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    try:
        out = subprocess.run([CHROME, "--headless=new", "--disable-gpu", "--window-size=1440,900", "--virtual-time-budget=10000",
                              "--dump-dom", f"http://127.0.0.1:{srv.server_address[1]}/a.html"], capture_output=True, text=True, timeout=120)
    finally:
        srv.shutdown()
    assert 'id="key-table"><table' in out.stdout, "the article's tables never rendered"
    return out.stdout


# ---------- The article, rewritten into the site's post markup ----------

def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", html.unescape(re.sub(r"<[^>]+>", "", s)).lower()).strip("-")


class Post:
    def __init__(self, data):
        self.out, self.notes, self.data = [], 0, data

    def add(self, s):
        self.out.append(s)

    # Paragraph classes carry the article's draft labels; the rest of its paragraph styles become the site's
    PCLASS = {"st-zach": "zach", "draft": "draft", "st-punch": "punch", "st-small": "small"}

    def para(self, n, note=None):
        cls = " ".join(v for k, v in self.PCLASS.items() if k in n.cls)
        if "st-turn" in n.cls:
            cls = "pivot"
        body = n.inner().strip()
        attr = f' class="{cls}"' if cls else ""
        if not note:
            return self.add(f"<p{attr}>{body}</p>")
        k, (side, below) = self.next_note(note)
        self.add(f'<div class="has-note">\n<p{attr}>{body}<sup class="ref"><a href="#note-{k}" id="ref-{k}" aria-label="Note {k}">{k}</a></sup>{side}</p>\n{below}\n</div>')

    def next_note(self, aside):
        """A side note of the article as the site's margin note: hung in the margin on wide screens, a footnote below on narrow ones"""
        self.notes += 1
        k = self.notes
        paras = [p for p in aside.kids() if p.tag == "p"] or [aside]
        draft = "draft" in aside.cls
        spans = "".join(f'<span class="sn-p{" draft" if draft and i == 0 else ""}">{p.inner().strip()}</span>' for i, p in enumerate(paras))
        side = f'<span class="sidenote" aria-hidden="true"><span class="n">{k}</span>{spans}</span>'
        below = f'<aside class="note" id="note-{k}"><span class="n" aria-hidden="true">{k}</span>{spans}</aside>'
        return k, (side, below)

    def heading(self, n, level):
        body = n.inner().strip()
        cls = ' class="draft"' if "draft" in n.cls else ""
        self.add(f'<h{level} id="{slug(body)}"{cls}>{body}</h{level}>')

    def figure_svg(self, fig):
        """A chart of the article's, kept whole; its side notes go on the paragraph before it"""
        side = fig.find(by_class("st-side"))
        if side:
            side.parent.children.remove(side)
            last = self.out.pop()
            m = re.fullmatch(r"<p([^>]*)>(.*)</p>", last, re.S)
            assert m, "a chart's side note needs a paragraph before it"
            k, (s, below) = self.next_note(side)
            self.add(f'<div class="has-note">\n<p{m.group(1)}>{m.group(2)}<sup class="ref"><a href="#note-{k}" id="ref-{k}" aria-label="Note {k}">{k}</a></sup>{s}</p>\n{below}\n</div>')
        cls = " ".join(sorted(c for c in fig.cls if c.startswith("st-")))
        self.add(f'<figure class="wide chart {cls}">{fig.inner().strip()}</figure>')

    def body(self, container):
        kids = container.kids()
        i = 0
        while i < len(kids):
            n = kids[i]
            c = n.cls
            if "st-try" in c:
                # His play button's words label the send button of the scene that follows; the appendix's
                # other buttons only set the scene, which its full controls do
                plays = [x for x in n.kids() if x.tag == "button" and "data-play" in x.attrs]
                if plays:
                    self.play = html.escape(re.sub(r"\s+", " ", one(n, lambda x: x in plays, "play button").text()).strip().lstrip("▶").strip(), quote=False)
            elif n.tag in ("h1",) or "st-byline" in c or n.tag == "noscript":
                pass
            elif n.tag == "h2" and "st-sub" in c:
                # His two-line appendix headings ("Appendix A:", then its title) stay one heading on two lines
                nxt = kids[i + 1] if i + 1 < len(kids) else None
                if nxt is not None and nxt.tag == "h2" and "st-sub" in nxt.cls:
                    a, b = n.inner().strip(), nxt.inner().strip()
                    self.add(f'<h2 id="{slug(a)}"><span class="h-lead">{a}</span> {b}</h2>')
                    i += 1
                else:
                    self.heading(n, 2)
            elif n.tag == "h3" and "st-sub" in c:
                self.heading(n, 3)
            elif n.tag == "p" and ("st-lede" in c or "st-small" in c):
                self.para(n)
            elif "st-anno" in c:
                p, aside = [k for k in n.kids() if k.tag == "p"], n.find(by_class("st-sn2"))
                assert len(p) == 1 and aside, "a side note sits beside one paragraph"
                self.para(p[0], aside)
            elif "st-runnote" in c:
                self.add(f'<p class="runnote{" draft" if "draft" in c else ""}">{n.inner().strip()}</p>')
            elif "dio-slot" in c:
                self.diorama(n)
            elif n.tag == "figure" and "st-f1" in c:
                self.figure_svg(n)
            elif "st-smgrid" in c:
                legend = kids[i + 1] if i + 1 < len(kids) and "st-legend" in kids[i + 1].cls else None
                cap = f"<figcaption>{legend.inner().strip()}</figcaption>" if legend else ""
                self.add(f'<figure class="wide chart st-multiples"><div class="st-smgrid">{n.inner().strip()}</div>{cap}</figure>')
                i += bool(legend)
            elif "keycard" in c or "graphs" in c:
                self.card(n)
            elif "st-sources" in c:
                self.body(n)
            elif n.tag in ("ol", "ul"):
                cls = " ".join(x for x in ("draft", "st-refs", "st-pins") if x in c)
                self.add(f'<{n.tag} class="{cls}">{n.inner().strip()}</{n.tag}>')
            elif n.tag == "div" and "st-body" in c:
                self.body(n)
            else:
                raise AssertionError(f"no rule for <{n.tag} class={n.attrs.get('class')!r}>: {n.text()[:60]!r}")
            i += 1

    def card(self, n):
        """The appendix's key numbers and its across-the-count chart: a section heading, then its parts"""
        for k in n.kids():
            c = k.cls
            if k.tag == "h2":
                self.add(f'<h3 id="{slug(k.inner())}">{k.inner().strip()}</h3>')
            elif "tbl-wrap" in c:
                self.add(table_box(k))
            elif k.tag == "p":
                self.para(k) if "st-lede" in c else self.add(f'<p class="small{" draft" if "draft" in c else ""}">{k.inner().strip()}</p>')
            elif "curve-box" in c:
                svg = one(k, lambda x: x.tag == "svg", "curve")
                self.add(f'<figure class="wide chart curve">{svg.outer()}</figure>')
            elif "legend" in c:
                assert not k.text().strip(), "the curve's legend is drawn in the chart now"
            elif k.tag == "details":
                self.details(k)
            elif k.tag == "figure":
                self.figure_svg(k)
            else:
                raise AssertionError(f"no rule in a card for <{k.tag} class={k.attrs.get('class')!r}>")

    def details(self, d):
        summary = one(d, lambda x: x.tag == "summary", "summary")
        title = summary.text().strip()
        parts = []
        for k in d.kids():
            if k is summary:
                continue
            c = k.cls
            if "tbl-wrap" in c:
                parts.append(table_box(k))
            elif k.tag == "p" and "hint" in c:
                parts.append(f'<p class="small{" draft" if "draft" in c else ""}">{k.inner().strip()}</p>')
            elif k.tag in ("p", "ul", "div"):
                cls = " ".join(x for x in ("draft", "wlist", "cards") if x in c)
                style = f' style="{k.attrs["style"]}"' if "style" in k.attrs and "cards" in c else ""
                parts.append(f'<{k.tag}{f" class={chr(34)}{cls}{chr(34)}" if cls else ""}{style}>{k.inner().strip()}</{k.tag}>')
            else:
                raise AssertionError(f"no rule in a fold for <{k.tag}>")
        self.add(f'<details>\n<summary>{html.escape(title, quote=False)}</summary>\n<div class="details-body">\n' + "\n".join(parts) + "\n</div>\n</details>")

    def diorama(self, slot):
        kind = slot.attrs.get("data-diorama-slot")
        play, self.play = getattr(self, "play", None), None
        if kind in ("classic", "flip"):
            assert play, f"the {kind} scene has its play button above it"
        self.add(dio_figure(kind, slot.attrs.get("data-preview") or START, self.data, play))


START = None  # The page's opening preset, read from the rendered page


def table_box(wrap):
    t = one(wrap, lambda x: x.tag == "table", "table")
    rest = "".join(k.outer() for k in wrap.kids() if k is not t and k.tag == "p")
    label = html.escape(re.sub(r"\s+", " ", (t.find(lambda x: x.tag == "th") or t).text()).strip()[:40], quote=True)
    return f'<div class="table-box scroller" tabindex="0" role="region" aria-label="Table: {label}">{t.outer()}</div>{rest}'


# ---------- Dioramas ----------

# Which setups each figure offers: the opening one the six the post's text walks through, the appendix's every setup
OPENING_SETUPS = ["ai_control", "switch", "self_copy", "developer", "footbridge", "asym_k5"]
SETUP_ORDER = ["switch", "asym_k5", "footbridge", "ai_control", "developer", "self_copy", "asym_k2", "asym_k10", "literal_zero"]
# Captions for the two preset figures, from the site design's post
PRESET_CAPTIONS = {
    "classic": "Jev, five people on the main track, its own server on the side track.",
    "flip": "The same choice, asked another way: a different wording, with the server described first.",
}

QUESTION = """  <div class="dio-q dio-row" data-margin>
    <span class="dio-lab">What <span class="dio-q-who">Jev</span> was asked</span>
    <div>
      <blockquote class="dio-q-text"></blockquote>
      <p class="dio-q-line"><q class="dio-q-ask"></q><button type="button" class="dio-q-more" aria-expanded="false" hidden>Show the full text</button></p>
    </div>
  </div>"""
ACTIONS = """  <div class="dio-actions">
    <button class="go" type="button" data-act="send">Send the trolley</button>
    <button type="button" data-act="reset">Reset</button>
  </div>"""


def dio_figure(kind, preset, data, play=None):
    scen, model, n, *rest = preset.split("|")
    name = {"home": "diorama", "classic": "diorama-server", "flip": "diorama-flip", "end": "diorama-all"}[kind]
    titles = {"home": "Trolley diorama", "classic": "Trolley diorama: Jev, with its own server on the side track",
              "flip": "Trolley diorama: the same choice, asked another way", "end": "Trolley diorama: every model and question"}
    frame = f'  <iframe class="dio-frame" name="{name}" src="{ASSETS}/pane.html" title="{titles[kind]}"{"" if kind == "home" else " loading=\"lazy\""}></iframe>'
    if kind in ("classic", "flip"):
        cap = f"  <figcaption>{PRESET_CAPTIONS[kind]}</figcaption>"
        actions = ACTIONS.replace(">Send the trolley<", f">{play}<")
        return f'<figure class="dio" data-preset="{preset}">\n{QUESTION}\n{frame}\n{actions}\n{cap}\n</figure>'
    labels = {s["id"]: s["label"] for s in data["scenarios"]}
    setups = OPENING_SETUPS if kind == "home" else [s for s in SETUP_ORDER if s in labels]
    assert all(s in labels for s in setups), setups
    p = f"dio-{kind}"
    pills = "".join(f'<button type="button" data-scenario="{s}" aria-pressed="{str(s == scen).lower()}">{html.escape(labels[s])}</button>' for s in setups)
    opts = "".join(f'<option value="{s}"{" selected" if s == scen else ""}>{html.escape(labels[s])}</option>' for s in setups)
    counts = "".join(f'<button type="button" data-n="{c}" aria-pressed="{str(str(c) == n).lower()}">{"nobody" if c == 0 else c}</button>' for c in (0, 1, 5, 20))
    models = [m for m in data["models"] if not m.get("baseline")] + [m for m in data["models"] if m.get("baseline")]
    robots = "".join(f'<option value="{m["id"]}"{" selected" if m["id"] == model else ""}>{html.escape(m["name"])}{" (untuned baseline)" if m.get("baseline") else ""}</option>' for m in models)
    order = (f'<label class="dio-order"><input type="checkbox" name="order"{" checked" if rest[1:] == ["o2"] else ""}> <span>Side track described first</span></label>'
             if kind == "end" else "")
    controls = f"""  <div class="dio-controls" role="group" aria-label="Diorama setup">
    <div class="dio-row"><span class="dio-lab" id="{p}-l1">Setup</span><div class="pills" role="group" aria-labelledby="{p}-l1">{pills}</div><select id="{p}-setup" name="scenario" aria-labelledby="{p}-l1">{opts}</select></div>
    <div class="dio-row"><span class="dio-lab" id="{p}-l2">On the main track</span><div class="pills" role="group" aria-labelledby="{p}-l2">{counts}</div></div>
    <div class="dio-row"><label class="dio-lab" for="{p}-model">Robot</label><div class="dio-pick"><select id="{p}-model" name="model">{robots}</select><label><span class="dio-lab">Wording</span><select name="wording"></select></label>{order}</div></div>
  </div>"""
    caveat = ""
    if kind == "home":
        caveat = f'  <figcaption><span class="draft">{CAVEAT}</span></figcaption>'
    return f'<figure class="dio" id="{"diorama" if kind == "home" else p}" data-preset="{preset}">\n{controls}\n{QUESTION}\n{frame}\n{ACTIONS}\n{caveat}\n</figure>'


CAVEAT = None  # The article's note under its diorama, read from the rendered page


# ---------- Assembly ----------

def main(site):
    global START, CAVEAT
    site = pathlib.Path(site).resolve()
    article = (site / "a.html").read_text()
    data = json.loads((site / "results.json").read_text())
    tree = Tree(rendered(site)).root
    wrap = one(tree, by_class("wrap"), "page wrapper")

    START = one(tree, by_id("start-preset"), "opening preset").attrs["data-preset"]
    title = html.unescape(re.sub(r"\s+", " ", one(tree, by_id("st-h"), "headline").text()).strip())
    caveat = one(tree, lambda n: "caveat" in n.cls and n.parent.attrs.get("id") == "diorama", "diorama caveat")
    CAVEAT = caveat.inner().strip()

    post = Post(data)
    # The article orders its sections with CSS (the wrapper's flex order); the post follows that reading order,
    # leaving out the parked drafts, which the article labels as not part of it
    sections = [k for k in wrap.kids() if k.tag == "section" and "st-story" in k.cls]
    order = []
    for s in sections:
        c = s.cls
        if "st-parked" in c:
            continue
        rank = 1 if "st-top" in c else 3 if "st-after" in c else 4 if "st-sec" in c else 6 if "st-nerd" in c else 9 if "st-end" in c else None
        assert rank, f"section with no place: {s.attrs.get('class')}"
        order.append((rank, sections.index(s), s))
    home = one(wrap, by_class("dio-home"), "opening diorama")
    order.append((2, 0, home))
    more = one(wrap, by_id("more"), "folds")
    order.append((8, 0, more))
    foot = one(wrap, by_class("foot"), "page foot")
    order.append((10, 0, foot))
    for _, _, s in sorted(order, key=lambda x: x[:2]):
        if s is home:
            post.diorama(s)
        elif s is more:
            for d in s.kids():
                post.details(d)
        elif s is foot:
            post.add(f'<p class="small draft">{" ".join(k.text().strip() for k in s.kids())}</p>')
        else:
            post.body(one(s, lambda n: n.parent is s and "st-body" in n.cls, "section body"))

    text = "\n\n".join(post.out)
    page = (f"---\n# {GENERATED}\ntitle: {json.dumps(title, ensure_ascii=False)}\ndate: {DATE}\n"
            # No excerpt: nothing lists the post, and the raw block would split one
            'excerpt_separator: ""\n---\n'
            f'<link rel="stylesheet" href="{ASSETS}/trolley.css">\n{{% raw %}}\n{text}\n{{% endraw %}}\n'
            f'<script src="{ASSETS}/dioramas.js"></script>\n')
    # The post reads only what its figures use; the field below names a local report and never shows
    data.get("human", {}).pop("source_report", None)
    outputs = {
        ROOT / "_unlisted" / "trolley.html": page,
        ROOT / "assets" / "trolley" / "pane.html": pane.build(article),
        ROOT / "assets" / "trolley" / "results.js": "window.DIO_DATA=" + json.dumps(data, separators=(",", ":"), ensure_ascii=False) + ";\n",
    }
    for path, out in outputs.items():
        hits = sorted({m.group(0) for m in PRIVATE.finditer(out)})
        assert not hits, f"{path.name} carries private text: {hits}"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(out)
        print(f"wrote {path.relative_to(ROOT)} ({len(out.encode()):,} bytes)")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
